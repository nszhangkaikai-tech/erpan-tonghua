// 从已安装的 lucide-static 提取 SVG，生成 旧图标名 -> lucide 定义 的 TS 映射
// 输出: miniprogram/src/components/Icon/lucide-icons.ts
import fs from 'fs'
import path from 'path'

const LUCIDE_DIR = '/Users/zhangkai/.workbuddy/binaries/node/workspace/node_modules/lucide-static/icons'
const OUT = path.resolve('miniprogram/src/components/Icon/lucide-icons.ts')

// 旧名 -> lucide 文件名（不带 .svg）或 { lucide, filled }
const MAP = {
  'arrow-right': 'arrow-right',
  'award': 'award',
  'bell': 'bell',
  'book-open': 'book-open',
  'check': 'check',
  'chevron-left': 'chevron-left',
  'chevron-right': 'chevron-right',
  'clock': 'clock',
  'compass': 'compass',
  'copy': 'copy',
  'edit': 'pencil',
  'folder': 'folder',
  'gift': 'gift',
  'headphones': 'headphones',
  'heart': 'heart',
  'heart-filled': { lucide: 'heart', filled: true },
  'home': 'home',
  'info': 'info',
  'library': 'library',
  'logout': 'log-out',
  'message-circle': 'message-circle',
  'mic': 'mic',
  'moon': 'moon',
  'pause': 'pause',
  'play': 'play',
  'plus': 'plus',
  'refresh': 'refresh-cw',
  'search': 'search',
  'settings': 'settings',
  'share': 'share',
  'sparkles': 'sparkles',
  'star': 'star',
  'trash': 'trash-2',
  'user': 'user',
  'volume': 'volume-2',
  'x': 'x'
}

function extractBody(file) {
  const svg = fs.readFileSync(file, 'utf8')
  const m = svg.match(/<svg[^>]*>([\s\S]*?)<\/svg>/)
  if (!m) throw new Error('no svg in ' + file)
  return m[1].trim()
}

const out = {}
const missing = []
for (const [oldName, v] of Object.entries(MAP)) {
  const lucide = typeof v === 'string' ? v : v.lucide
  const filled = typeof v === 'object' ? !!v.filled : false
  const file = path.join(LUCIDE_DIR, lucide + '.svg')
  if (!fs.existsSync(file)) {
    missing.push(oldName + ' -> ' + lucide + '.svg (缺失)')
    continue
  }
  out[oldName] = { body: extractBody(file), filled: filled }
}

if (missing.length) {
  console.error('缺失的 lucide 图标:')
  missing.forEach(function (m) { console.error('  ' + m) })
}

let ts = '// AUTO-GENERATED by scripts/gen-lucide-icons.mjs — 不要手动编辑\n'
ts += '// 图标来源: lucide-static (MIT)。旧图标名 -> lucide SVG 内部路径。\n'
ts += '// 渲染: Icon 组件把 body 包进 <svg viewBox="0 0 24 24" fill/stroke=color> 后转 data URI。\n'
ts += 'export interface LucideIconDef {\n'
ts += '  /** SVG 内部路径（不含外层 <svg> 标签） */\n'
ts += '  body: string\n'
ts += '  /** 是否实心填充（用于 heart-filled 等） */\n'
ts += '  filled?: boolean\n'
ts += '}\n\n'
ts += 'export const LUCIDE_ICONS: Record<string, LucideIconDef> = {\n'
for (const [k, val] of Object.entries(out)) {
  ts += '  ' + JSON.stringify(k) + ': { body: ' + JSON.stringify(val.body) + ', filled: ' + (val.filled ? 'true' : 'false') + ' },\n'
}
ts += '}\n'

fs.writeFileSync(OUT, ts, 'utf8')
console.log('已生成 ' + OUT)
console.log('成功映射 ' + Object.keys(out).length + ' 个，缺失 ' + missing.length + ' 个')
