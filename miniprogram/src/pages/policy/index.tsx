const TABS = [
  { key: 'user', label: '用户协议' },
  { key: 'child', label: '儿童信息保护政策' },
] as const

export default function Policy() {
  const router = useRouter()
  const initial = router.params.type === 'child' ? 'child' : 'user'
  const [tab, setTab] = useState<typeof initial>(initial)
  const content = tab === 'child' ? CHILD_POLICY : USER_AGREEMENT

  const handleBack = () => {
    if (Taro.getCurrentPages().length > 1) {
      Taro.navigateBack()
    } else {
      Taro.reLaunch({ url: '/pages/welcome/index' })
    }
  }

  return (
    <View className='policy'>
      <View className='policy__navbar'>
        <View className='policy__back' onClick={handleBack}>
          <Icon name='chevron-left' size={40} color='#18181b' />
        </View>
        <Text className='policy__nav-title'>协议与政策</Text>
        <View className='policy__nav-spacer' />
      </View>

      <View className='policy__tabs'>
        {TABS.map(t => (
          <View
            key={t.key}
            className={`policy__tab ${tab === t.key ? 'policy__tab--active' : ''}`}
            onClick={() => setTab(t.key)}
          >
            <Text className='policy__tab-text'>{t.label}</Text>
          </View>
        ))}
      </View>

      <View className='policy__body'>
        <Text className='policy__meta'>生效日期：2026 年 8 月 7 日　更新日期：2026 年 8 月 7 日</Text>
        {content.map((section, idx) => (
          <View className='policy__section' key={idx}>
            <Text className='policy__section-title'>{section.h}</Text>
            {section.p.map((para, pidx) => (
              <Text className='policy__para' key={pidx}>{para}</Text>
            ))}
          </View>
        ))}
        <View className='policy__footer-space' />
      </View>
    </View>
  )
}
